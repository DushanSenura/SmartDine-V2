/** Reference data needed by every environment. Idempotent. */
export async function seedMenuReferenceData(prisma: PrismaClient) {
  for (const [index, name] of CATEGORIES.entries()) {
    const slug = slugify(name);
    await prisma.menuCategory.upsert({
      where: { slug },
      update: {},
      create: { name, slug, sortOrder: index * 10 },
    });
  }
  for (const name of ALLERGENS) {
    await prisma.allergen.upsert({ where: { name }, update: {}, create: { name } });
  }
}

