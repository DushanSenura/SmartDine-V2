/** Development-only: choices on a few dishes so ordering has something to configure. Idempotent. */
export async function seedDemoModifiers(prisma: PrismaClient, branchId: string) {
  for (const [name, modifiers] of Object.entries(DEMO_MODIFIERS)) {
    const item = await prisma.menuItem.findFirst({
      where: { branchId, name, deletedAt: null },
      include: { _count: { select: { modifiers: true } } },
    });
    if (!item || item._count.modifiers > 0) continue;
    await prisma.menuItemModifier.createMany({
      data: modifiers.map((m, sortOrder) => ({ ...m, menuItemId: item.id, sortOrder })),
    });
  }
}
