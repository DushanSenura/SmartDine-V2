/** Development-only sample menu so the public site is not empty on first run. Idempotent. */
export async function seedDemoMenu(prisma: PrismaClient, branchId: string) {
  if ((await prisma.menuItem.count({ where: { branchId } })) > 0) return;
  const categories = new Map((await prisma.menuCategory.findMany()).map((c) => [c.name, c.id]));
  const allergens = new Map((await prisma.allergen.findMany()).map((a) => [a.name, a.id]));

  for (const item of DEMO) {
    await prisma.menuItem.create({
      data: {
        branchId,
        categoryId: categories.get(item.category)!,
        name: item.name,
        slug: slugify(item.name),
        shortDescription: item.short,
        description: item.short,
        price: item.price,
        comparePrice: item.compare,
        preparationTime: item.prep,
        calories: item.calories,
        spiceLevel: item.spice ?? 0,
        vegetarian: item.vegetarian || item.vegan || false,
        vegan: item.vegan ?? false,
        halal: item.halal ?? false,
        featured: item.featured ?? false,
        popular: item.popular ?? false,
        newItem: item.isNew ?? false,
        kitchenStation: item.station,
        mealPeriods: item.periods ?? [],
        allergens: { connect: item.allergens.map((name) => ({ id: allergens.get(name)! })) },
      },
    });
  }
}

